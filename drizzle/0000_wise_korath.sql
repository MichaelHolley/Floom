CREATE TABLE `plants` (
	`id` integer PRIMARY KEY AUTOINCREMENT NOT NULL,
	`photo` text NOT NULL,
	`name` text NOT NULL,
	`location` text NOT NULL,
	`commonName` text NOT NULL,
	`botanicalName` text NOT NULL,
	`light` text NOT NULL,
	`wateringSummerMin` integer NOT NULL,
	`wateringSummerMax` integer NOT NULL,
	`wateringWinterMin` integer NOT NULL,
	`wateringWinterMax` integer NOT NULL,
	`wateringNote` text NOT NULL,
	`fertilizingSummerMin` integer NOT NULL,
	`fertilizingSummerMax` integer NOT NULL,
	`fertilizingWinterMin` integer,
	`fertilizingWinterMax` integer,
	`fertilizingNote` text NOT NULL,
	`substrate` text NOT NULL,
	`repottingYears` integer NOT NULL,
	`repottingNote` text NOT NULL,
	`toxicPets` integer NOT NULL,
	`toxicChildren` integer NOT NULL,
	`toxicityNote` text NOT NULL,
	`difficulty` text NOT NULL,
	`frostMinTemp` integer,
	`overwinteringNote` text NOT NULL,
	`tips` text NOT NULL
);
